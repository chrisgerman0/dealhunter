import type { Coords } from "@/types/deal";

const EARTH_RADIUS_MILES = 3958.8;

export function haversineMiles(a: Coords, b: Coords): number {
  const toRad = (d: number) => (d * Math.PI) / 180;
  const dLat = toRad(b.lat - a.lat);
  const dLng = toRad(b.lng - a.lng);
  const lat1 = toRad(a.lat);
  const lat2 = toRad(b.lat);
  const h =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(lat1) * Math.cos(lat2) * Math.sin(dLng / 2) ** 2;
  return 2 * EARTH_RADIUS_MILES * Math.asin(Math.min(1, Math.sqrt(h)));
}

/** UK-ish bounds used to reject garbage query params. */
export function isUkishCoord(lat: number, lng: number): boolean {
  return lat >= 49 && lat <= 61 && lng >= -9 && lng <= 2;
}

export function parseCoordParam(value: string | null): number | null {
  if (value == null || value.trim() === "") return null;
  const n = Number(value);
  return Number.isFinite(n) ? n : null;
}
